_REACT = """# ReAct 范式

## 核心循环
ReAct 的名字来自 Reasoning 与 Acting 的组合，2022 年由 Yao 等人提出。
它的核心是一个三拍循环：先想（Thought），再动（Action），然后看结果（Observation），
如此往复直到模型认为可以给出最终答案。Thought 本身不产生副作用，但它把隐式的推理
变成了显式的文本，后面的决策建立在这段文字之上，因此决策质量明显更稳定。

## 为什么要交替
纯推理的模型没有外部信息来源，遇到需要实时数据或精确计算的问题就会编造。
纯行动路线的模型虽然会调用工具，却不做规划，调错了也不知道如何补救。
ReAct 让两者交替，用 Observation 把模型从"猜"拉回"看"，用 Thought 保持规划能力。

## 工程上必须补的东西
论文不会告诉你模型会卡住。生产环境至少需要四道保险：最大步数上限、
重复调用的签名检测、工具异常转成可读观察、以及超长结果的截断。
其中重复检测最容易被忽略——只设最大步数只是"慢慢死"，
必须让模型知道自己卡住了，它才会换策略。
"""

_RAG = """# 检索增强生成

## 完整链路
RAG 的流程是：文档解析、切分成块、用嵌入模型编码成向量、写入向量库；
用户提问时把问题也编码成向量并做相似度检索，取回若干片段拼进提示词，
让模型基于这些片段作答并给出引用来源。它能缓解幻觉、支持私有知识，
而且不需要重新训练模型。

## 切分策略
固定长度切分实现最简单，但会把一句话甚至一个词从中间截断。
递归切分按段落、句子、词逐级尝试，尽量在语义边界处断开。
标题感知切分利用文档自身的结构，把同一章节的内容放在一起。
重叠（overlap）是常用补偿：相邻块共享一部分文本，避免答案正好落在边界上。

## 检索与重排
向量检索擅长语义相似，但对专有名词、编号、型号这类字面匹配不敏感。
BM25 这类稀疏检索恰好相反。所以生产上常用混合检索：
两路各召回一批候选，再用 RRF 之类的融合算法合并，最后用交叉编码器重排。
重排之所以有效，是因为向量相似度高不等于真正相关。
"""

_MEMORY = """# Agent 记忆体系

## 三层结构
Agent 记忆通常分三层。工作记忆是当前任务的临时状态，用完即弃；
会话记忆是本次对话的上下文，受窗口长度约束；长期记忆跨会话存在，
一般落在向量库里按需检索。三层的时间尺度和读写频率完全不同，
混在一起管理是常见的架构错误。

## 压缩与遗忘
会话变长时有三种处理：滑动窗口丢掉最早的内容、把早期对话做摘要压缩、
或者把关键事实抽成结构化字段落库。滑动窗口最便宜但会丢信息，
摘要压缩效果好但本身要花一次模型调用，结构化抽取最贵但最可靠。
遗忘策略同样重要——长期记忆只增不减，检索精度会随时间下降。

## 冲突处理
同一条事实被多次写入时会产生冲突。常见做法是带上时间戳与来源，
检索时优先返回更新的版本，并在提示词里明确告诉模型"以下信息可能已过期"。
"""

_MCP = """# 模型上下文协议

## 它解决什么问题
MCP 是一个开放协议，目标是让工具提供方和使用方解耦。
在它之前，每接一个模型客户端就要重写一遍工具适配层，M 个客户端乘 N 个工具
等于 M×N 份适配代码。MCP 把它变成 M+N：工具方实现一次 Server，
客户端实现一次 Client，双方按协议通信。

## 三个角色
Host 是最终用户面对的应用，Client 由 Host 创建、负责与单个 Server 保持连接，
Server 暴露能力。Server 可以提供的三样东西是 Tools（可调用的动作）、
Resources（可读取的数据）、Prompts（预设的提示模板）。
传输方式常见两种：本地的标准输入输出，以及远端的 HTTP 加事件流。

## 与函数调用的关系
函数调用是模型侧的调用格式，MCP 是连接层的协议，两者不在一个层次上。
一个 MCP Server 暴露的工具，最终仍然要转成函数调用的声明才能让模型看见。
MCP 真正的价值在于权限边界与复用，而不是让模型更聪明。
"""

_EVAL = """# Agent 效果评测

## 为什么难
单轮问答可以只比对最终答案，Agent 不行——它是一串动作。
同一个正确答案可能来自一条捷径，也可能来自十五步试错。
所以评测必须同时看结果和轨迹：任务是否完成、工具调用是否正确、
步骤数是否合理、成本是否可接受。

## 常用指标
结果侧看任务成功率与答案正确性；过程侧看工具调用准确率、参数正确率、
无效调用率、平均步数；成本侧看每次任务的 token 数与延迟分位数。
检索类系统还要单独看检索质量：Recall@k 衡量相关文档有没有被召回，
MRR 衡量第一个相关结果排得靠不靠前。

## 方法
规则断言最可靠但覆盖有限；模型当评委扩展性好，但有位置偏见和长度偏见，
需要人工抽检校准；人工评估最准但最贵，通常只用在小规模校准集上。
无论用哪种，都必须有**固定的回归集**，否则你无法判断一次改动是变好还是变坏。
"""

_LONG_DOCS = [_REACT, _RAG, _MEMORY, _MCP, _EVAL]


def _make_long_docs() -> list[Document]:
    names = ["react", "rag", "memory", "mcp", "evaluation"]
    titles = ["ReAct 范式", "检索增强生成", "Agent 记忆体系", "模型上下文协议", "Agent 效果评测"]
    return [
        Document(id=f"doc-{name}", title=title, text=text, tags=("long",))
        for name, title, text in zip(names, titles, _LONG_DOCS)
    ]


