def stats() -> dict:
    kinds: dict[str, int] = {}
    for q in QUERIES:
        kinds[q.kind] = kinds.get(q.kind, 0) + 1
    return {
        "documents": len(DOCUMENTS),
        "long_documents": sum(1 for d in DOCUMENTS if d.is_long),
        "short_documents": sum(1 for d in DOCUMENTS if not d.is_long),
        "total_chars": sum(len(d.text) for d in DOCUMENTS),
        "queries": len(QUERIES),
        "query_kinds": kinds,
    }
