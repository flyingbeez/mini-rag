"""语料与评测集。

**评测集是整个仓库最重要的文件。** 没有它，你就只能靠"感觉检索效果变好了"来调参。

设计要点：
  * 语料里混了 **5 篇长文档**（多章节，800–1500 字）和 **15 篇短文档**。
    长文档才会被切分，切分策略的差异才有意义。
  * 评测集的 query 刻意分成三类：
      - `keyword`  —— 查询词与原文几乎一致（BM25 的主场）
      - `semantic` —— 换了说法，字面不重合（向量检索的主场）
      - `mixed`    —— 一部分字面重合、一部分需要语义理解
    这样消融表才能解释"为什么混合检索更好"，而不是只给出一个总数。
  * 每条 query 标注 `relevant`（相关文档 id 集合），可以算 Recall@k 和 MRR。
"""

from __future__ import annotations

from dataclasses import dataclass, field

__all__ = ["Document", "Query", "DOCUMENTS", "QUERIES", "documents_by_id", "stats"]


@dataclass
class Document:
    id: str
    title: str
    text: str
    tags: tuple[str, ...] = ()

    @property
    def is_long(self) -> bool:
        """长文档 = 会被切分成多块的那种。用标签标记，而不是靠字数猜。"""
        return "long" in self.tags


